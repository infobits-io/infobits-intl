    public function emojiFlag(): string
    {
        $code = $this->value;
        $base = 0x1F1E6 - 65;
        $first = ord($code[0]) + $base;
        $second = ord($code[1]) + $base;

        return mb_chr($first) . mb_chr($second);
    }

    public static function fromAlpha3(string $code): ?self
    {
        $upper = strtoupper($code);
        foreach (self::cases() as $case) {
            if ($case->alpha3Code() === $upper) {
                return $case;
            }
        }

        return null;
    }

    public static function fromNumeric(int $code): ?self
    {
        foreach (self::cases() as $case) {
            if ($case->numericCode() === $code) {
                return $case;
            }
        }

        return null;
    }
